#!/usr/bin/env node
// Collects ../deployments/<chainId>.json (written by script/Deploy.s.sol or script/LocalDemo.s.sol)
// into src/generated/deployments.ts. Dry-run files (*.dry-run.json) are ignored.
// Usage: node scripts/sync-deployments.mjs [deploymentsDir]
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const appRoot = resolve(here, '..')
const dir = resolve(appRoot, process.argv[2] ?? '../deployments')
const out = join(appRoot, 'src/generated/deployments.ts')

const isAddr = (v) => typeof v === 'string' && /^0x[0-9a-fA-F]{40}$/.test(v)
const deployments = {}
if (existsSync(dir)) {
  for (const f of readdirSync(dir).sort()) {
    const m = /^(\d+)\.json$/.exec(f)
    if (!m) continue
    const j = JSON.parse(readFileSync(join(dir, f), 'utf8'))
    for (const k of ['processor', 'circuit', 'lens', 'erc6551Registry', 'accountImplementation']) {
      if (!isAddr(j[k])) throw new Error(`${f}: bad or missing address "${k}"`)
    }
    if (Number(j.chainId) !== Number(m[1])) throw new Error(`${f}: chainId ${j.chainId} does not match file name`)
    deployments[m[1]] = {
      chainId: Number(j.chainId),
      deployBlock: Number(j.deployBlock ?? 0),
      launchEndBlock: Number(j.launchEndBlock ?? 0),
      processor: j.processor,
      circuit: j.circuit,
      lens: j.lens,
      erc6551Registry: j.erc6551Registry,
      accountImplementation: j.accountImplementation,
    }
    console.log(`deployment: chain ${m[1]} processor ${j.processor}`)
  }
}
mkdirSync(dirname(out), { recursive: true })
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/sync-deployments.mjs from deployments/*.json. Do not edit.\n` +
    `import type { Deployment } from '../config/types.ts'\n\n` +
    `export const generatedDeployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)}\n`,
)
console.log(`wrote ${out} (${Object.keys(deployments).length} chain(s))`)
